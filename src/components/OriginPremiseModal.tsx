export function OriginPremiseModal({ open, onClose }: OriginPremiseModalProps) {
  useEffect(() => {
    if (!open) {
      return;
    }

    function handleKeyDown(event: KeyboardEvent) {
      if (event.key === "Escape") {
        onClose();
      }
    }

    window.addEventListener("keydown", handleKeyDown);
    return () => window.removeEventListener("keydown", handleKeyDown);
  }, [onClose, open]);

  if (!open) {
    return null;
  }

  return (
    <div className="premise-overlay" role="presentation">
      <section
        className="premise-window"
        role="dialog"
        aria-modal="true"
        aria-labelledby="premise-origin-title"
      >
        <div className="premise-ornament" aria-hidden="true">
          ◱ ╿
        </div>
        <header className="premise-header">
          <p id="premise-origin-title">{PREMISE_TITLE}</p>
          <button type="button" onClick={onClose} aria-label="Close premise origin">
            <X size={18} />
          </button>
        </header>
        <div className="premise-divider" aria-hidden="true" />
        <div className="premise-scroll">
          {PREMISE_PARAGRAPHS.map((paragraph) => (
            <p key={paragraph}>{paragraph}</p>
          ))}
        </div>
        <footer className="premise-footer">
          <span>—◱ ╿</span>
          <i aria-hidden="true">▔▔▔▔▔▔▔▔▔▔▔▔▔▔▔▔▔▔▔▔</i>
          <button type="button" onClick={onClose}>
            Seal Record
          </button>
        </footer>
      </section>
    </div>
  );
}
